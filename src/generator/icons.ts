import { PropertyType } from '../types';

export function getPropertyIconName(type: PropertyType, propName?: string): string {
	if (propName === 'file' || propName === 'file.name') return 'file-text';
	if (propName?.startsWith('formula.')) return 'calculator';

	switch (type) {
		case 'number':
			return 'hash';
		case 'date':
			return 'calendar';
		case 'checkbox':
			return 'check-square';
		case 'list':
			return 'tag';
		case 'link':
			return 'link-2';
		case 'text':
		default:
			return 'type';
	}
}

export function renderIconSvg(iconName: string, extraClass = ''): string {
	const cls = extraClass ? `b2h-icon ${extraClass}` : 'b2h-icon';
	return `<svg class="${cls}" aria-hidden="true"><use href="#lucide-${iconName}"></use></svg>`;
}

